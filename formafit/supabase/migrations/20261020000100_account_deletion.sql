-- Self-service account deletion. Deleting the auth user cascades to every private table
-- (all user_id / owner_id columns reference auth.users ON DELETE CASCADE). Storage objects
-- are removed by the application through the Storage API before this function is called.

create or replace function public.delete_my_account()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
begin
  if v_uid is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;
  delete from auth.users where id = v_uid;
end;
$$;

revoke all on function public.delete_my_account() from public, anon;
grant execute on function public.delete_my_account() to authenticated;
